"""Optional, cached RDAP enrichment; never a direct target probe.

NOT WIRED INTO ANY WORKFLOW. This network-capable helper (queries rdap.org) is retained for API
compatibility only. Cloud/ASN attribution uses operator-imported ASN maps instead, so no RDAP
traffic is generated by DomainRecon menus or CLI commands. Any future integration must add an
operation-specific authorization record and engagement switch before use.
"""
from __future__ import annotations

import json
import os
from pathlib import Path
from urllib.error import HTTPError, URLError
from urllib.request import Request, urlopen

from domainrecon.core.scope import ScopePolicy


def lookup_public_ip(ip_address: str, scope: ScopePolicy, cache_directory: Path, *, timeout: int = 10) -> dict:
    """Get public registration data through the IANA bootstrap endpoint with a cache."""
    ip_address = scope.require_public_ip(ip_address)
    cache_directory.mkdir(parents=True, exist_ok=True)
    cache = cache_directory / f"{ip_address.replace(':', '_')}.json"  # ':' would create an NTFS alternate data stream
    if cache.is_file():
        return json.loads(cache.read_text(encoding="utf-8"))
    request = Request(f"https://rdap.org/ip/{ip_address}", headers={"User-Agent": "DomainRecon/2.0"})
    try:
        with urlopen(request, timeout=timeout) as response:  # fixed HTTPS service
            payload = response.read(1_048_577)
        if len(payload) > 1_048_576:
            raise ValueError("RDAP response exceeds 1 MiB limit")
        data = json.loads(payload.decode("utf-8"))
    except (HTTPError, URLError, TimeoutError, UnicodeDecodeError, json.JSONDecodeError) as exc:
        return {"ip": ip_address, "status": "failed", "error": str(exc)}
    temporary = cache.with_suffix(".json.tmp")
    temporary.write_text(json.dumps(data, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    os.replace(temporary, cache)  # atomic: a partially written cache entry is never read back
    return data
